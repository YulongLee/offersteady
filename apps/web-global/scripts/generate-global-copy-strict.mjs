import fs from "node:fs";
import path from "node:path";
import ts from "typescript";

const projectRoot = path.resolve(import.meta.dirname, "..");
const sourceRoot = path.join(projectRoot, "src");
const outputPath = path.join(sourceRoot, "global-copy.generated.ts");
const catalog = JSON.parse(fs.readFileSync(path.join(projectRoot, "scripts/global-copy-catalog.json"), "utf8"));
const HAN = /[\u3400-\u9fff]/;
const normalize = (value) => value.trim().replace(/\s+/g, " ");

const fnv1a = (value) => {
  let hash = 0x811c9dc5;
  for (let index = 0; index < value.length; index += 1) {
    hash ^= value.charCodeAt(index);
    hash = Math.imul(hash, 0x01000193);
  }
  return (hash >>> 0).toString(36);
};

const occurrences = new Map();
for (const name of fs.readdirSync(sourceRoot).filter((entry) => /\.(ts|tsx)$/.test(entry) && entry !== "global-copy.generated.ts" && !entry.includes(".test."))) {
  const filePath = path.join(sourceRoot, name);
  const sourceFile = ts.createSourceFile(
    filePath,
    fs.readFileSync(filePath, "utf8"),
    ts.ScriptTarget.Latest,
    true,
    name.endsWith(".tsx") ? ts.ScriptKind.TSX : ts.ScriptKind.TS,
  );
  const visit = (node) => {
    if ((ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node) || ts.isJsxText(node)) && HAN.test(node.text)) {
      const source = normalize(node.text);
      if (source) {
        const location = sourceFile.getLineAndCharacterOfPosition(node.getStart(sourceFile));
        const locations = occurrences.get(source) ?? [];
        locations.push(`${name}:${location.line + 1}`);
        occurrences.set(source, locations);
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(sourceFile);
}

const missing = [...occurrences.entries()].filter(([source]) => typeof catalog[source] !== "string" || !catalog[source].trim());
if (missing.length) {
  const details = missing.map(([source, locations]) => `- ${JSON.stringify(source)} (${locations.slice(0, 5).join(", ")})`).join("\n");
  throw new Error(`Global product copy is missing ${missing.length} explicit translation(s):\n${details}`);
}
const invalid = [...occurrences.keys()].filter((source) => HAN.test(catalog[source]));
if (invalid.length) throw new Error(`Global translations still contain Chinese: ${invalid.map(JSON.stringify).join(", ")}`);

const rows = [...occurrences.keys()].sort().map((source) => [fnv1a(source), catalog[source]]);
fs.writeFileSync(
  outputPath,
  `// Generated by scripts/generate-global-copy-strict.mjs. Do not edit by hand.\nexport const globalCopyByHash: Readonly<Record<string, string>> = ${JSON.stringify(Object.fromEntries(rows), null, 2)};\n`,
);
console.log(`Generated ${rows.length} explicit Global English copy entries.`);
