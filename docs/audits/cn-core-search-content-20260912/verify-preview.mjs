// Read-only local Nginx checks. Never follows or submits a production business action.
import assert from 'node:assert/strict';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';

const candidate = resolve(process.argv[2]);
const output = resolve(process.argv[3]);
const require = createRequire(resolve(candidate, 'apps/web/package.json'));
const { JSDOM } = require('jsdom');
const base = 'http://127.0.0.1:18988';
const canonicalOrigin = 'https://mianshiwen.cn';
const agents = {
  ordinary: 'Mozilla/5.0 (compatible; Local-Content-QA/1.0)',
  baidu: 'Mozilla/5.0 (compatible; Baiduspider/2.0; +http://www.baidu.com/search/spider.html)',
};
const core = ['/', '/pricing', '/download', '/features/realtime-interview', '/features/ai-interview-assistant'];
const evidence = { scope: 'local isolated Nginx only; not production verification', capturedAt: new Date().toISOString(), core: [], sitemap: [], resources: [], links: [], entrypoints: [] };
const documents = new Map();
await mkdir(output, { recursive: true });
async function read(path, ua = agents.ordinary) {
  const response = await fetch(base + path, { headers: { 'User-Agent': ua }, redirect: 'manual', signal: AbortSignal.timeout(10000) });
  const html = await response.text();
  const doc = new JSDOM(html, { url: base + path }).window.document;
  return { response, html, doc };
}
function checkPage(path, { response, html, doc }) {
  assert.equal(response.status, 200, path);
  assert.equal(doc.querySelectorAll('h1').length, 1, path + ' H1');
  assert.equal(doc.querySelectorAll('title').length, 1);
  assert.ok(doc.title.length > 8);
  assert.ok(doc.querySelector('meta[name="description"]')?.content.length > 15);
  assert.equal(doc.querySelector('link[rel="canonical"]')?.href, canonicalOrigin + path);
  const robots = [...doc.querySelectorAll('meta[name="robots"]')].map(n => n.content).join(' ') + ' ' + (response.headers.get('x-robots-tag') ?? '');
  assert.doesNotMatch(robots, /noindex|none/i);
  const main = doc.querySelector('main')?.textContent ?? '';
  assert.ok(main.trim().length > 150, path + ' meaningful raw body');
  const csp = response.headers.get('content-security-policy') ?? '';
  const schemas = [...doc.querySelectorAll('script[type="application/ld+json"]')].map(n => {
    const hash = 'sha256-' + createHash('sha256').update(n.textContent).digest('base64');
    assert.ok(csp.includes(hash), path + ' missing exact CSP hash');
    return JSON.parse(n.textContent);
  });
  return { path, status: response.status, title: doc.title, h1: doc.querySelector('h1').textContent, description: doc.querySelector('meta[name="description"]').content, canonical: doc.querySelector('link[rel="canonical"]').href, robots: robots.trim() || 'not set (indexable)', rawBodyLength: main.trim().length, htmlBytes: Buffer.byteLength(html), schemaTypes: schemas.flatMap(s => s['@graph']?.map(n => n['@type']) ?? [s['@type']]) };
}
for (const path of core) {
  let original;
  for (const [agent, ua] of Object.entries(agents)) {
    const page = await read(path, ua);
    evidence.core.push({ agent, ...checkPage(path, page) });
    if (original) assert.equal(page.html, original, path + ' UA parity');
    original = page.html;
    documents.set(path, page.doc);
    await writeFile(resolve(output, `${path.replaceAll('/', '_') || 'home'}-${agent}.html`), page.html);
  }
}
const sitemapResponse = await fetch(base + '/sitemap.xml');
assert.equal(sitemapResponse.status, 200);
const sitemap = await sitemapResponse.text();
const urls = [...sitemap.matchAll(/<loc>([^<]+)<\/loc>/g)].map(m => m[1]);
assert.equal(urls.length, 30);
for (const url of urls) {
  const path = new URL(url).pathname;
  const page = await read(path, agents.baidu);
  evidence.sitemap.push(checkPage(path, page));
  documents.set(path, page.doc);
}
assert.equal(new Set(evidence.sitemap.map(p => p.title)).size, 30);
const linked = new Map();
const guideSource = await readFile(resolve(candidate, 'apps/web/src/guide-content.ts'), 'utf8');
for (const path of core) {
  const doc = documents.get(path);
  for (const node of doc.querySelectorAll('a[href]')) {
    const url = new URL(node.getAttribute('href'), base + path);
    if (url.origin !== base || /^\/(api|r)\//.test(url.pathname)) continue;
    linked.set(url.pathname + url.search + url.hash, url);
  }
}
for (const [href, url] of linked) {
  const page = await read(url.pathname + url.search);
  assert.equal(page.response.status, 200, 'internal link: ' + href);
  // Authenticated app anchors may be generated by JS; public anchors must exist in HTML.
  let anchorEvidence = 'not applicable';
  if (url.hash && !/^\/(app|login)(\/|$)/.test(url.pathname)) {
    const id = decodeURIComponent(url.hash.slice(1));
    if (url.pathname === '/guide' && ['desktop', 'live', 'billing'].includes(id)) {
      // Existing guide uses the hash as a client-side chapter selector, not a DOM id.
      assert.ok(guideSource.includes(`id: "${id}"`));
      anchorEvidence = 'existing JS chapter selector; raw HTML has no chapter anchor; browser verification required';
    } else {
      assert.ok(page.doc.getElementById(id), 'missing public anchor: ' + href);
      anchorEvidence = 'present in raw HTML';
    }
  }
  evidence.links.push({ href, status: page.response.status, anchorEvidence });
}
const resources = new Set();
for (const doc of documents.values()) {
  for (const n of doc.querySelectorAll('script[src], link[rel="stylesheet"], img[src]')) {
    const value = n.getAttribute('src') ?? n.getAttribute('href');
    if (value?.startsWith('/')) resources.add(value);
  }
}
for (const path of resources) {
  const response = await fetch(base + path, { method: 'HEAD' });
  assert.equal(response.status, 200, 'resource: ' + path);
  evidence.resources.push({ path, status: response.status });
}
for (const path of ['/login', '/app/billing', '/app/interviews/new', '/app/devices']) {
  const response = await fetch(base + path, { method: 'HEAD' });
  assert.equal(response.status, 200);
  evidence.entrypoints.push({ path, status: response.status, scope: 'HTML entry only; no login, order or device action performed' });
}
const missing = await fetch(base + '/guides/nonexistent-local-content-check', { redirect: 'manual' });
assert.equal(missing.status, 404);
await writeFile(resolve(output, 'raw-html-evidence.json'), JSON.stringify(evidence, null, 2));
console.log(`PASS: ${core.length} pages x 2 UAs; 30 sitemap pages; ${linked.size} public/internal links; ${resources.size} local assets; 4 readonly entrypoints; unknown URL is 404.`);
